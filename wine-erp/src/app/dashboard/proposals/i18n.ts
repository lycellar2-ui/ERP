/**
 * Split and display bilingual title according to current locale.
 * If title contains ' / ', format according to selected language.
 */
export function formatBilingualTitle(title: string | null | undefined, locale: AppLocale) {
    if (!title) return { main: '—', sub: null }
    if (!title.includes(' / ')) {
        return { main: title, sub: null }
    }
    const parts = title.split(' / ')
    const viPart = parts[0]?.trim() || ''
    const enPart = parts.slice(1).join(' / ').trim() || ''

    if (locale === 'en') {
        return {
            main: enPart || viPart,
            sub: viPart && viPart !== enPart ? viPart : null,
        }
    }
    return {
        main: viPart || enPart,
        sub: enPart && enPart !== viPart ? enPart : null,
    }
}
